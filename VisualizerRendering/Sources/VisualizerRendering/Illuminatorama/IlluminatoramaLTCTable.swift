// ── ILLUMINATORAMA LTC TABLE — BAKED INTO THE BINARY ─────────────────────────
//
// The 16×16 LTC fit (see `IlluminatoramaLTC`) is a CONSTANT: it is a function of
// the GGX BRDF and the table dimensions and of nothing else — not the scene, the
// materials, the view, the device or the platform. It was nevertheless being
// re-derived by a Nelder-Mead optimizer inside every `IlluminatoramaRenderer.init`,
// at ~4.7 M double-precision BRDF evaluations a go.
//
// That cost 2639 ms of Daydream Home's 2776 ms cold-launch `bridgeInit` — 95 % of
// it — because the engine package builds unoptimised in Debug and the fit is 29×
// slower at `-Onone` (2576 ms) than at `-O` (88 ms). It also explained the shape of
// the mystery: the fit is cached process-wide by device, so a SECOND renderer in
// the same process cost ~20 ms, which had made the cost look like device/driver
// startup. Measured with `IlluminatoramaInitTiming`, 2026-08-02.
//
// So the table is fitted once, offline, and its texels are checked in here as
// literals — free at any optimisation level, and 88 ms saved in Release too.
// `IlluminatoramaLTCTableTests` re-runs the real fitter and diffs it against these
// numbers, so the table cannot silently go stale if the BRDF or the fit changes:
// that becomes a red test, and the test writes the regenerated literals out for
// pasting back in. `VIZ_ILLUMI_LTC_RUNTIME_FIT=1` restores the fit-at-launch path.
//
